#![forbid(unsafe_code)]
//! `cargo run --release --bin import`: load the Aug 24 backup, the Aug 17 crawl and the Sep 14
//! live pulls into Postgres, copy media into the served media dir, and build the redirect table.
//! Idempotent: it truncates and re-imports. Ambiguities go to research/import-log.md.

use anyhow::{Context, Result};
use serde::Deserialize;
use sqlx::{postgres::PgPoolOptions, PgPool, Row};
